def tile(ch):
    px = [[0] * 8 for _ in range(8)]
    rows = G.get(ch, G['?'])
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            if c == '#':
                sx, sy = x + 2, y + 1
                if px[sy][sx] == 0:
                    px[sy][sx] = 1
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            if c == '#':
                px[y][x + 1] = 15
    out = []
    for y in range(8):
        for x in range(0, 8, 2):
            out.append(px[y][x] | (px[y][x + 1] << 4))
    return out


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    data = []
    for c in range(32, 96):
        data += tile(chr(c))
    path = os.path.join(root, "arm9", "source", "font_etch.c")
    with open(path, "w") as f:
        f.write("/* AUTOGENERATED by tools/gen_font.py -- do not edit. */\n")
        f.write("#include <stdint.h>\n\n")
        f.write("/* ASCII 32..95, 4bpp 8x8 tiles: 15 = glyph, 1 = stamped shadow */\n")
        f.write("const uint8_t font_etch_tiles[%d] __attribute__((aligned(4))) = {\n" % len(data))
        for i in range(0, len(data), 16):
            f.write("    " + ",".join("0x%02X" % b for b in data[i:i + 16]) + ",\n")
        f.write("};\n")
    print("wrote", path)


if __name__ == "__main__":
    main()
